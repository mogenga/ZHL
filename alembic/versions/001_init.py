"""PB baseline: Phase 0 shared-contract DDL (migrations/001_init.sql).

Revision ID: 001_init
Revises:
Create Date: 2026-10-11

Notes
-----
The Phase 0 schema (12 tables + enums + EXCLUDE / triggers / column-level
permissions + seed data) was applied OUTSIDE alembic, via::

    psql $ZHL_DB -f migrations/001_init.sql

This revision is a *baseline marker*: it exists purely so the alembic
revision chain 001_init -> 002_reinspection_scope is complete and every
``alembic`` command can resolve the graph. ``upgrade()`` is a no-op because
the DDL already ran; it asserts the baseline shape so a bare database
(carefully stamped, or freshly created) cannot be advanced to head without
the 001 DDL applied.

Before running 002 on a Phase 0 database, stamp the baseline::

    alembic stamp 001_init
    alembic upgrade head

Downgrade deliberately refuses to drop the 001 objects: the DDL was not
generated by alembic, so its reverse DDL is unknown (triggers, EXCLUDE
constraints, revocations, seed rows). Rolling a database back to pre-001
is not supported; rebuild it from scratch instead.
"""

from __future__ import annotations

from sqlalchemy import inspect as sa_inspect

from alembic import op

# revision identifiers, used by Alembic.
revision = "001_init"
down_revision = None
branch_labels = None
depends_on = None


def upgrade() -> None:
    """No-op: the 001 DDL was applied by ``psql -f migrations/001_init.sql``.

    Assert the baseline shape so a missing DDL is caught before 002 runs.
    Any of the 12 Phase 0 tables plus the Phase B target tables must exist.
    """
    bind = op.get_bind()
    inspector = sa_inspect(bind)
    existing = set(inspector.get_table_names())
    required = {
        "quality_rule_versions",
        "delivery_batches",
        "module_inspections",
        "reinspections",
        "quality_incidents",
        "evidence",
    }
    missing = required - existing
    if missing:
        raise RuntimeError(
            "baseline 001_init cannot be applied on this database: missing "
            f"tables {sorted(missing)}. Apply the Phase 0 DDL first: "
            "psql $ZHL_DB -f migrations/001_init.sql, then run "
            "alembic stamp 001_init."
        )


def downgrade() -> None:
    raise RuntimeError(
        "downgrade below 001_init is not supported: the Phase 0 DDL "
        "(migrations/001_init.sql) was not generated by alembic, so its "
        "reverse DDL is unknown. Rebuild the database from scratch instead."
    )
